export const dictionaries: Record<Lang, Dict> = { en, de };

export function detectLang(): Lang {
  return navigator.language?.toLowerCase().startsWith("de") ? "de" : "en";
}

const I18nContext = createContext<{ lang: Lang; t: Dict; setLang: (l: Lang) => void }>({
  lang: "en",
  t: en,
  setLang: () => {},
});

export function I18nProvider(props: { lang: Lang; setLang: (l: Lang) => void; children: ReactNode }) {
  return (
    <I18nContext.Provider value={{ lang: props.lang, t: dictionaries[props.lang], setLang: props.setLang }}>
      {props.children}
    </I18nContext.Provider>
  );
}

export const useI18n = () => useContext(I18nContext);
